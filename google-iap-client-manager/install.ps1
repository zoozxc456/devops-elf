#Requires -Version 7.2
[CmdletBinding()]
param([string]$BinDir, [switch]$Setup, [switch]$NoPath, [string]$ProfilePath, [switch]$Help)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/scripts/common.ps1"
if ($Help) {
    '用法：pwsh -NoProfile -File install.ps1 [-BinDir PATH] [-Setup] [-NoPath] [-ProfilePath PATH]'
    '預設 ~/.local/bin；也可用 BIN_DIR 指定。安裝原生 PowerShell iap，不需要 Bash。'
    return
}
if (-not $BinDir) { $BinDir = if ($env:BIN_DIR) { $env:BIN_DIR } else { Join-Path $HOME '.local/bin' } }
$BinDir = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($BinDir)
[void][IO.Directory]::CreateDirectory($BinDir)
$target = Join-Path $BinDir 'iap.ps1'
$source = Join-Path $PSScriptRoot 'iap.ps1'
if ([IO.Path]::GetFullPath($target) -eq [IO.Path]::GetFullPath($source)) { throw '安裝目錄不可為原始碼目錄。' }
Assert-IapRegularTarget $target
if (Test-Path -LiteralPath $target) {
    $existing = [IO.File]::ReadAllText($target).Replace("`r`n", "`n")
    if (-not ($existing.StartsWith('# Generated by google-iap-client-manager/install.ps1') -or
        $existing.StartsWith("#Requires -Version 7.2`n# Native PowerShell client;"))) {
        throw "拒絕覆寫既有檔案：$target"
    }
}
$support = Join-Path $BinDir '.iap'
[void][IO.Directory]::CreateDirectory((Join-Path $support 'scripts'))
[void][IO.Directory]::CreateDirectory((Join-Path $support 'completions'))
Copy-Item -LiteralPath $source -Destination $target -Force
foreach ($name in @('setup.ps1','common.ps1','manage.ps1')) {
    Copy-Item -LiteralPath (Join-Path $PSScriptRoot "scripts/$name") -Destination (Join-Path $support "scripts/$name") -Force
}
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'completions/iap.ps1') -Destination (Join-Path $support 'completions/iap.ps1') -Force
Write-IapPrivateFile (Join-Path $support 'powershell-source') ($PSScriptRoot + "`n")
Write-Host "已複製安裝：$target"
$installedVersion = & $target version
Write-Host "✔ 安裝版本：$installedVersion"
if (-not $NoPath) {
    $separator = [string][IO.Path]::PathSeparator
    if ($IsWindows -and -not $ProfilePath) {
        $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
        $parts = @($userPath -split ';' | Where-Object { $_ })
        if ($BinDir.TrimEnd('\','/') -notin @($parts | ForEach-Object { $_.TrimEnd('\','/') })) {
            $newPath = (@($BinDir) + $parts) -join ';'
            [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
            Write-Host '✔ 已加入使用者 PATH（新工作階段生效）。'
        } else { Write-Host '✔ 使用者 PATH 已設定。' }
    } else {
        if (-not $ProfilePath) { $ProfilePath = $PROFILE.CurrentUserAllHosts }
        $ProfilePath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($ProfilePath)
        Assert-IapRegularTarget $ProfilePath
        $marker = '# iap PATH: ' + $BinDir
        $existing = if (Test-Path -LiteralPath $ProfilePath) { [IO.File]::ReadAllText($ProfilePath) } else { '' }
        if ($marker -cnotin ($existing -split '\r?\n')) {
            [void][IO.Directory]::CreateDirectory((Split-Path $ProfilePath -Parent))
            if (Test-Path -LiteralPath $ProfilePath) {
                $backup = "$ProfilePath.backup-$([guid]::NewGuid().ToString('N'))"
                Write-IapPrivateFile $backup ''
                [IO.File]::WriteAllBytes($backup, [IO.File]::ReadAllBytes($ProfilePath))
                Write-Host "PowerShell profile 備份：$backup"
            }
            $quoted = Quote-IapPowerShell $BinDir
            $block = "`n$marker`nif ($quoted -notin (`$env:PATH -split [regex]::Escape([string][IO.Path]::PathSeparator))) {`n    `$env:PATH = $quoted + [IO.Path]::PathSeparator + `$env:PATH`n}`n"
            [IO.File]::AppendAllText($ProfilePath, $block, [Text.UTF8Encoding]::new($false))
            Write-Host "✔ 已加入 PATH：$ProfilePath"
        } else { Write-Host "✔ PATH 已設定：$ProfilePath" }
    }
    if ($BinDir -notin ($env:PATH -split [regex]::Escape($separator))) { $env:PATH = $BinDir + $separator + $env:PATH }
    Write-Host '✔ 本次 PowerShell 工作階段 PATH 已更新；若透過 pwsh -File 執行，父終端機請開啟新工作階段。'
}
Write-Host ('Tab 補全（可加到 $PROFILE）：. ' + (Quote-IapPowerShell (Join-Path $support 'completions/iap.ps1')))
Write-Host '建立設定：iap setup'
Write-Host '新增連線：iap new（保留既有設定）'
if ($Setup) { & (Join-Path $support 'scripts/setup.ps1') }
