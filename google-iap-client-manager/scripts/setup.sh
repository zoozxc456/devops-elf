#!/usr/bin/env bash
# Bash 3.2+。只建立連線設定，不登入 Google Cloud 或啟動連線。
set +x
set -euo pipefail
umask 077

CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/iap"
TARGET="${IAP_CONF:-$CONF_DIR/hosts}"
ADD_NEW=false
if [[ -z ${IAP_CONF:-} ]]; then
  for file in hosts.yaml hosts.yml hosts.json; do
    if [[ -f "$CONF_DIR/$file" ]]; then TARGET="$CONF_DIR/$file"; break; fi
  done
fi
usage() {
  cat <<'HELP'
用法：bash scripts/setup.sh [--config PATH]
      iap setup [--config PATH]
      iap new [--config PATH]  新增一組連線，保留既有設定並備份

互動建立 SSH / port tunnel 設定，可加入多台主機與連線入口。
輸出依 IAP_CONF、XDG_CONFIG_HOME/iap 或 ~/.config/iap 選擇；--config 優先。
依副檔名產生 YAML / JSON / 純文字；YAML / JSON 輸出需要 Python 3。
既有設定預設不覆寫，確認後重建並備份；不會沿用原有欄位。
不會登入、變更 gcloud config 或啟動連線。
HELP
}
while [[ $# -gt 0 ]]; do
  case $1 in
    --new) ADD_NEW=true; shift ;;
    --config) [[ $# -ge 2 && -n $2 ]] || { usage >&2; exit 1; }; TARGET=$2; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 1 ;;
  esac
done
fail() { printf '%s\n' "$*" >&2; exit 1; }
ask() {
  local label=$1 default=$2 validator=$3 input
  while true; do
    printf '%s' "$label" >&2
    [[ -z "$default" ]] || printf ' [%s]' "$default" >&2
    printf ': ' >&2
    IFS= read -r input || fail '已取消，未寫入設定。'
    input=${input:-$default}
    if "$validator" "$input"; then ANSWER=$input; return; fi
    printf '格式不符，請重新輸入。\n' >&2
  done
}
yes_no() {
  local input
  while true; do
    printf '%s [%s]: ' "$1" "$2" >&2
    IFS= read -r input || fail '已取消，未寫入設定。'
    [[ -n $input ]] || { if [[ $2 == Y/n ]]; then input=y; else input=n; fi; }
    case $input in
      y|Y|yes|YES) return 0 ;;
      n|N|no|NO) return 1 ;;
      *) printf '請輸入 y 或 n。\n' >&2 ;;
    esac
  done
}
token() { [[ $1 =~ ^[a-zA-Z0-9][a-zA-Z0-9._-]*$ ]]; }
name_value() {
  token "$1" || return 1
  case $1 in export|help|remove|reset|uninstall|new|setup|ls|list|show|edit|import|to-yaml|version|update|self-update|names) return 1 ;; esac
}
cloud_value() { [[ $1 == - ]] || token "$1"; }
instance_value() { [[ $1 =~ ^([a-zA-Z0-9._-]+@)?[a-zA-Z0-9][a-zA-Z0-9._-]*$ ]]; }
connection_type() { [[ $1 == ssh || $1 == tunnel ]]; }
port() { [[ $1 =~ ^[1-9][0-9]{0,4}$ ]] && (( 10#$1 <= 65535 )); }
endpoint() { [[ -n $1 && ! $1 =~ [[:cntrl:]] ]]; }

[[ ! -L $TARGET ]] || fail "拒絕覆寫符號連結：$TARGET"
if [[ -e $TARGET ]]; then
  [[ -f $TARGET ]] || fail "目標不是一般檔案：$TARGET"
  if [[ $ADD_NEW == false ]]; then
    printf '注意：將重建整份設定，所有既有連線會被替換。只要新增請用 iap new，修改單一連線請用 iap edit <name>。\n' >&2
    yes_no "已有 ${TARGET}，將用新輸入重建並備份原檔，是否繼續？" y/N || exit 0
  fi
fi
case $TARGET in
  *.yaml|*.yml|*.json) command -v python3 >/dev/null || fail '產生 YAML / JSON 設定需要 Python 3。' ;;
esac
WORK=$(mktemp -d "${TMPDIR:-/tmp}/iap-setup.XXXXXX")
STAGED=
cleanup() { rm -rf "$WORK"; [[ -z $STAGED ]] || rm -f "$STAGED"; }
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

USED='|'
if [[ $ADD_NEW == false && -f $TARGET ]]; then cp "$TARGET" "$WORK/original"; fi
if [[ $ADD_NEW == true && -f $TARGET ]]; then
  cp "$TARGET" "$WORK/original"
  case $TARGET in
    *.yaml|*.yml|*.json)
      python3 - "$TARGET" "$WORK/existing.json" "$WORK/names" <<'PY'
import json
import subprocess
import sys

text = open(sys.argv[1], encoding='utf-8-sig').read()
try:
    data = json.loads(text)
except ValueError:
    if sys.argv[1].endswith('.json'):
        raise
    try:
        import yaml
        data = yaml.safe_load(text)
    except ImportError:
        data = json.loads(subprocess.check_output(['yq', '-o=json', '.', sys.argv[1]], text=True))
if not isinstance(data, dict) or not isinstance(data.get('hosts'), dict):
    raise SystemExit('設定必須包含 hosts map，未修改設定。')
with open(sys.argv[2], 'w', encoding='utf-8') as target:
    json.dump(data, target, ensure_ascii=False)
with open(sys.argv[3], 'w', encoding='utf-8') as target:
    target.write('\n'.join(data['hosts']) + '\n')
PY
      ;;
    *) awk '!/^[[:space:]]*(#|$|>)/ {print $1}' "$TARGET" > "$WORK/names" ;;
  esac
  while IFS= read -r existing; do USED="$USED$existing|"; done < "$WORK/names"
fi
printf 'IAP 設定精靈\nproject / zone 填 - 使用 gcloud config；不會變更 gcloud 的預設值。\n' >&2
PROJECT=-; ZONE=-
if [[ $ADD_NEW == false ]]; then
  ask '共用 Google Cloud project' '-' cloud_value; PROJECT=$ANSWER
  ask '共用 zone' '-' cloud_value; ZONE=$ANSWER
fi
printf '# IAP hosts — generated by iap setup\n' > "$WORK/hosts"
while true; do
  while true; do
    ask '連線名稱（不可重複或使用指令名稱）' '' name_value; NAME=$ANSWER
    [[ $USED != *"|$NAME|"* ]] && break
    printf '名稱已存在，請換一個。\n' >&2
  done
  USED="$USED$NAME|"
  ask '連線類型 ssh / tunnel' ssh connection_type; TYPE=$ANSWER
  ask 'project' "$PROJECT" cloud_value; HOST_PROJECT=$ANSWER
  ask 'zone' "$ZONE" cloud_value; HOST_ZONE=$ANSWER
  ask 'VM instance（SSH 可填 user@instance）' "$NAME" instance_value; INSTANCE=$ANSWER
  if [[ $TYPE == tunnel ]]; then
    while [[ $INSTANCE == *@* ]]; do
      printf 'Tunnel 的 instance 不可包含 SSH 使用者。\n' >&2
      ask 'VM instance' "$NAME" token; INSTANCE=$ANSWER
    done
    ask '遠端 port（1–65535）' '' port; REMOTE_PORT=$ANSWER
    ask '本機 port（1–65535）' "$REMOTE_PORT" port; LOCAL_PORT=$ANSWER
    printf '%s tunnel %s %s %s %s %s\n' "$NAME" "$HOST_PROJECT" "$HOST_ZONE" "$INSTANCE" "$REMOTE_PORT" "$LOCAL_PORT" >> "$WORK/hosts"
  else
    printf '%s ssh %s %s %s\n' "$NAME" "$HOST_PROJECT" "$HOST_ZONE" "$INSTANCE" >> "$WORK/hosts"
  fi
  while yes_no '加入連線入口（網址或連線字串）？' y/N; do
    ask '入口（可填「標籤 網址」，支援 {port} / {rport}；請勿放密碼）' '' endpoint
    printf '  > %s\n' "$ANSWER" >> "$WORK/hosts"
  done
  [[ $ADD_NEW == false ]] || break
  yes_no '繼續加入另一個連線？' y/N || break
done

case $TARGET in
  *.yaml|*.yml|*.json)
    # JSON 同時是合法 YAML，不需要額外的 YAML 套件；使用 serializer 保留字面值。
    python3 - "$WORK/hosts" "$WORK/output" "$WORK/existing.json" "$ADD_NEW" <<'PY'
import json
import os
import sys

hosts = {}
with open(sys.argv[1], encoding="utf-8") as source:
    for line in source:
        if line.startswith("#"):
            continue
        if line.startswith("  > "):
            host.setdefault("endpoints", []).append(line[4:].rstrip("\n"))
            continue
        name, kind, project, zone, instance, *ports = line.split()
        host = {"type": kind, "instance": instance}
        hosts[name] = host
        if project != "-" or sys.argv[4] == 'true':
            host["project"] = project
        if zone != "-" or sys.argv[4] == 'true':
            host["zone"] = zone
        if ports:
            host.update(remote_port=int(ports[0]), local_port=int(ports[1]))
data = {'hosts': {}}
if os.path.exists(sys.argv[3]):
    with open(sys.argv[3], encoding='utf-8') as source:
        data = json.load(source)
if set(data['hosts']).intersection(hosts):
    raise SystemExit('名稱重複，未修改設定。')
data['hosts'].update(hosts)
with open(sys.argv[2], "w", encoding="utf-8") as target:
    json.dump(data, target, ensure_ascii=False, indent=2)
    target.write("\n")
PY
    ;;
  *)
    if [[ $ADD_NEW == true && -f "$WORK/original" ]]; then
      cp "$WORK/original" "$WORK/output"
      printf '\n' >> "$WORK/output"
      sed '1d' "$WORK/hosts" >> "$WORK/output"
    else cp "$WORK/hosts" "$WORK/output"; fi ;;
esac
if [[ -f "$WORK/original" ]]; then
  cmp -s "$TARGET" "$WORK/original" || fail '設定在輸入期間已變更，請重試，未寫入設定。'
fi
[[ ! -L $TARGET ]] || fail "拒絕覆寫符號連結：$TARGET"
mkdir -p "$(dirname "$TARGET")"
if [[ -f $TARGET ]]; then
  BACKUP=$(mktemp "${TARGET}.backup-XXXXXX")
  cp "$TARGET" "$BACKUP"
  chmod 600 "$BACKUP"
  printf '原檔備份：%s\n' "$BACKUP"
fi
STAGED=$(mktemp "${TARGET}.tmp-XXXXXX")
cp "$WORK/output" "$STAGED"
chmod 600 "$STAGED"
mv -f "$STAGED" "$TARGET"
STAGED=
printf '\n設定完成：%s\n檢查與連線：\n' "$TARGET"
printf 'IAP_CONF=%q iap ls\nIAP_CONF=%q iap %q\n' "$TARGET" "$TARGET" "$NAME"
