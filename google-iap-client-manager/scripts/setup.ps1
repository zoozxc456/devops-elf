#Requires -Version 7.2
[CmdletBinding()]
param([string]$Config, [switch]$New, [switch]$Help)
Set-PSDebug -Off
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/common.ps1"

if ($Help) {
    Write-Output @'
用法：pwsh -NoProfile -File scripts/setup.ps1 [-Config PATH]
      iap new [-Config PATH]  新增一組連線，保留既有設定並備份
互動建立多組 SSH / tunnel 與連線入口。只產生設定，不登入或連線。
路徑優先序：-Config、IAP_CONF、XDG_CONFIG_HOME/iap、~/.config/iap。
支援純文字、JSON 及 JSON 語法的 YAML，不需要額外套件。
重跑時重新輸入全部欄位；既有設定預設不覆寫，確認後備份。
'@
    return
}
function Ask([string]$Label, [string]$Default, [scriptblock]$Validate) {
    while ($true) {
        $prompt = if ($Default.Length) { "$Label [$Default]" } else { $Label }
        $value = Read-Host $prompt
        if ($null -eq $value) { throw '已取消，未寫入設定。' }
        if ($value.Length -eq 0) { $value = $Default }
        if (& $Validate $value) { return $value }
        Write-Host '格式不符，請重新輸入。'
    }
}
function Confirm([string]$Label) {
    while ($true) {
        $value = Read-Host "$Label [y/N]"
        if ($null -eq $value) { throw '已取消，未寫入設定。' }
        if ($value -eq '' -or $value -match '^(n|no)$') { return $false }
        if ($value -match '^(y|yes)$') { return $true }
        Write-Host '請輸入 y 或 n。'
    }
}
$token = { param($v) $v -cmatch '^[A-Za-z0-9][A-Za-z0-9._-]*$' }
$cloud = { param($v) $v -ceq '-' -or (& $token $v) }
$nameValidator = {
    param($v)
    (& $token $v) -and $v -cnotin @('export','help','remove','reset','uninstall','new','setup','ls','list','show','edit','import','to-yaml','version','update','self-update','names')
}
$port = { param($v) $v -cmatch '^[1-9][0-9]{0,4}$' -and [int]$v -le 65535 }
$target = if ($Config) { $Config } else { Get-IapConfigPath }
$target = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($target)
Assert-IapRegularTarget $target
if (-not $New -and (Test-Path -LiteralPath $target)) {
    Write-Host '注意：將重建整份設定，所有既有連線會被替換。只要新增請用 iap new，修改單一連線請用 iap edit <name>。'
    if (-not (Confirm "已有 ${target}，將重建並備份原檔，是否繼續？")) { return }
}

$structured = [IO.Path]::GetExtension($target) -in @('.json','.yaml','.yml')
$existingData = $null
$original = $null
if (-not $New -and (Test-Path -LiteralPath $target)) { $original = [IO.File]::ReadAllBytes($target) }
$usedNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
if ($New -and (Test-Path -LiteralPath $target)) {
    $original = [IO.File]::ReadAllBytes($target)
    if ($structured) {
        $existingData = Read-IapStructuredConfig $target
        foreach ($key in $existingData['hosts'].Keys) { [void]$usedNames.Add($key) }
    } else {
        foreach ($line in ([IO.File]::ReadAllLines($target))) {
            if ($line -notmatch '^\s*(#|$|>)') { [void]$usedNames.Add(($line.Trim() -split '\s+')[0]) }
        }
    }
}

Write-Host 'IAP 設定精靈；project / zone 填 - 使用 gcloud config。'
$project = '-'; $zone = '-'
if (-not $New) {
    $project = Ask '共用 Google Cloud project' '-' $cloud
    $zone = Ask '共用 zone' '-' $cloud
}
$hostsMap = [ordered]@{}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# IAP hosts — generated by PowerShell setup')
do {
    do {
        $name = Ask '連線名稱（不可重複或使用指令名稱）' '' $nameValidator
        $duplicate = $usedNames.Contains($name) -or $hostsMap.Contains($name)
        if ($duplicate) { Write-Host '名稱已存在，請換一個。' }
    } while ($duplicate)
    $kind = Ask '連線類型 ssh / tunnel' 'ssh' { param($v) $v -cin @('ssh','tunnel') }
    $hostProject = Ask 'project' $project $cloud
    $hostZone = Ask 'zone' $zone $cloud
    $instance = Ask 'VM instance（SSH 可填 user@instance）' $name {
        param($v) $v -cmatch '^([A-Za-z0-9._-]+@)?[A-Za-z0-9][A-Za-z0-9._-]*$'
    }
    $hostConfig = [ordered]@{ type = $kind; instance = $instance }
    if ($hostProject -ne '-' -or $New) { $hostConfig.project = $hostProject }
    if ($hostZone -ne '-' -or $New) { $hostConfig.zone = $hostZone }
    $line = "$name $kind $hostProject $hostZone $instance"
    if ($kind -eq 'tunnel') {
        while ($instance.Contains('@')) {
            Write-Host 'Tunnel 的 instance 不可包含 SSH 使用者。'
            $instance = Ask 'VM instance' $name $token
        }
        $hostConfig.instance = $instance
        $remotePort = Ask '遠端 port（1–65535）' '' $port
        $localPort = Ask '本機 port（1–65535）' $remotePort $port
        $hostConfig.remote_port = [int]$remotePort
        $hostConfig.local_port = [int]$localPort
        $line = "$name $kind $hostProject $hostZone $instance $remotePort $localPort"
    }
    $lines.Add($line)
    $endpoints = [Collections.Generic.List[string]]::new()
    while (Confirm '加入連線入口（網址或連線字串）？') {
        $value = Ask '入口（支援 {port} / {rport}，可填「標籤 網址」；請勿放密碼）' '' {
            param($v) $v.Length -gt 0 -and $v -notmatch '\p{Cc}'
        }
        $endpoints.Add($value)
        $lines.Add("  > $value")
    }
    if ($endpoints.Count) { $hostConfig.endpoints = $endpoints.ToArray() }
    $hostsMap[$name] = $hostConfig
} while (-not $New -and (Confirm '繼續加入另一個連線？'))

$content = if ($structured) {
    $data = if ($null -ne $existingData) { $existingData } else { [ordered]@{ hosts = [ordered]@{} } }
    foreach ($key in $hostsMap.Keys) { $data['hosts'][$key] = $hostsMap[$key] }
    (($data | ConvertTo-Json -Depth 100).Replace("`r`n", "`n")) + "`n"
} else { ($lines -join "`n") + "`n" }
[void][IO.Directory]::CreateDirectory((Split-Path $target -Parent))
Assert-IapRegularTarget $target
if ($null -ne $original) {
    if (-not (Test-Path -LiteralPath $target) -or
        [Convert]::ToBase64String([IO.File]::ReadAllBytes($target)) -cne [Convert]::ToBase64String($original)) {
        throw '設定在輸入期間已變更，請重試，未寫入設定。'
    }
}
if (Test-Path -LiteralPath $target) {
    $backup = "$target.backup-$([guid]::NewGuid().ToString('N'))"
    Write-IapPrivateFile $backup ''
    [IO.File]::WriteAllBytes($backup, [IO.File]::ReadAllBytes($target))
    Write-Host "原檔備份：$backup"
}
$staged = "$target.tmp-$([guid]::NewGuid().ToString('N'))"
try {
    Write-IapPrivateFile $staged $content
    if ($New -and -not $structured -and $null -ne $original) {
        $addition = [Text.Encoding]::UTF8.GetBytes("`n" + (($lines | Select-Object -Skip 1) -join "`n") + "`n")
        [IO.File]::WriteAllBytes($staged, [byte[]]($original + $addition))
    }
    [IO.File]::Move($staged, $target, $true)
} finally {
    if (Test-Path -LiteralPath $staged) { Remove-Item -LiteralPath $staged -Force }
}
Write-Host "設定完成：$target"
Write-Host ('$env:IAP_CONF = ' + (Quote-IapPowerShell $target))
Write-Host 'iap ls'
Write-Host ('iap ' + (Quote-IapPowerShell $name))
